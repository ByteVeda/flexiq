/** Free functions have no declaring type, so they are placed by name. */
const FREE_FUNCTIONS = {
  startExecutor: { group: "execution", receiver: "" },
  reservedSettingPrefixes: { group: "queue", receiver: "" },
};

/** The page and receiver for one symbol. `group: "other"` means unmapped. */
export function placementOf(symbol) {
  const placement = symbol.owner
    ? OWNERS[symbol.owner]
    : FREE_FUNCTIONS[symbol.name];
  return placement ?? { group: "other", receiver: "" };
}

/** Qualified name — the identity used by the allowlist and the ratchet. */
export function qualify(symbol) {
  return symbol.owner ? `${symbol.owner}.${symbol.name}` : symbol.name;
}

/** `__init__` is the constructor, and the docs spell it as the class. */
export function isConstructor(symbol) {
  return symbol.name === "__init__";
}

/**
 * Symbols the reference is expected to carry. `__repr__` and friends implement
 * a language protocol rather than a queue operation — leaving them out here
 * keeps them out of the generated pages *and* out of the coverage arithmetic,
 * so the allowlist stays a list of real judgement calls.
 */
export function documentable(symbols) {
  return symbols.filter(
    (symbol) => !/^__\w+__$/.test(symbol.name) || isConstructor(symbol),
  );
}

export function repoPath(relative) {
  return fileURLToPath(new URL(relative, REPO_ROOT));
}

export function snapshotPath(sdk) {
  return fileURLToPath(new URL(`${sdk}.json`, SNAPSHOT_DIR));
}

/** True when this checkout has the sources for `sdk` — see `collectInventories`. */
export function sourcesPresent(sdk) {
  const files = sourceFiles(sdk);
  return files.length > 0 && files.every((file) => existsSync(repoPath(file)));
}

/** Extract `sdk`'s surface from source. Sorted so the snapshot diffs cleanly. */
export function extractFromSource(sdk) {
  const { extract } = SOURCES[sdk];
  const files = sourceFiles(sdk);
  const symbols = files.flatMap((file) =>
    extract(readFileSync(repoPath(file), "utf8")),
  );
  symbols.sort(
    (a, b) =>
      (a.owner ?? "").localeCompare(b.owner ?? "") ||
      a.name.localeCompare(b.name) ||
      a.signature.localeCompare(b.signature),
  );
  // The pattern, not its expansion: a package-private file added beside the
  // public ones contributes no symbols, and should not churn the snapshot.
  return { sdk, source: SOURCES[sdk].files, symbols };
}

export function readSnapshot(sdk) {
  return JSON.parse(readFileSync(snapshotPath(sdk), "utf8"));
}

export function writeSnapshot(inventory) {
  const path = snapshotPath(inventory.sdk);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, `${JSON.stringify(inventory, null, 2)}\n`);
}

/** Every SDK, in registry order. */
export const SDKS = [...SDK_IDS];

/**
 * Both readings of every SDK's surface: what the committed snapshot says, and
 * what the sources say in this checkout (null when they aren't here). `current`
 * is whichever the caller should treat as the truth — source when available,
 * snapshot otherwise.
 */
export function collectInventories() {
  return new Map(
    SDKS.map((sdk) => {
      const path = snapshotPath(sdk);
      const snapshot = existsSync(path) ? readSnapshot(sdk) : null;
      const extracted = sourcesPresent(sdk) ? extractFromSource(sdk) : null;
      return [sdk, { snapshot, extracted, current: extracted ?? snapshot }];
    }),
  );
}
