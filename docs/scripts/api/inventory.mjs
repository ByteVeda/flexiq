// The machine-readable inventory of each SDK's public surface, and where it
// comes from.
//
// One rule picks the source per SDK: the single declaration file that
// enumerates the queue surface *under the names a user calls*. For Python and
// Node that is the native stub — the shells forward those names verbatim
// (`cancel_job`, `deadLettersAfter`). For Java it is the public `FlexiQ`
// interface, because the JNI facade spells the same methods `getJobJson`.
//
// The extracted result is committed as a snapshot under `content/api/`. That is
// not a cache: `sdks/node/native/index.d.ts` is generated by `pnpm
// build:native` and gitignored, so a clean checkout has no Node source at all
// and the gate would otherwise be unrunnable in the docs CI job.

import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { SDK_IDS } from "../../app/lib/sdk-registry.ts";
import { extractJava } from "./extract/java.mjs";
import { extractNode } from "./extract/node.mjs";
import { extractPython } from "./extract/python.mjs";

const REPO_ROOT = new URL("../../../", import.meta.url);
const SNAPSHOT_DIR = new URL("../../content/api/", import.meta.url);

/** Where each SDK's surface is declared, and how to read it. */
export const SOURCES = {
  python: {
    files: ["sdks/python/flexiq/_flexiq.pyi"],
    extract: extractPython,
    language: "python",
  },
  node: {
    files: ["sdks/node/native/index.d.ts"],
    extract: extractNode,
    language: "typescript",
    // Regenerated by `pnpm build:native`; absent on a clean checkout.
    generated: true,
  },
  java: {
    // The whole root package, not three named files: a public interface added
    // beside FlexiQ is exactly the surface this gate exists to notice, and the
    // extractor already drops package-private types (DefaultFlexiQ,
    // NamedQueue) on its own.
    files: ["sdks/java/src/main/java/org/byteveda/flexiq/*.java"],
    extract: extractJava,
    language: "java",
  },
};

/** Expand a source entry's trailing `*.ext` wildcard; plain paths pass through. */
function expand(pattern) {
  const star = pattern.indexOf("*");
  if (star === -1) {
    return [pattern];
  }
  const dir = pattern.slice(0, pattern.lastIndexOf("/"));
  const suffix = pattern.slice(star + 1);
  if (!existsSync(repoPath(dir))) {
    return [];
  }
  return readdirSync(repoPath(dir))
    .filter((entry) => entry.endsWith(suffix))
    .sort()
    .map((entry) => `${dir}/${entry}`);
}

/** Every file `sdk`'s surface is read from, wildcards resolved. */
export function sourceFiles(sdk) {
  return SOURCES[sdk].files.flatMap(expand);
}

