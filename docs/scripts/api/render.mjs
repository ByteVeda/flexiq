// Inventory → MDX.
//
// What is generated is deliberately narrow: the signature, its parameters,
// their defaults and the return type. Nothing here writes prose. The point is
// not to replace the writing — it is to stop the writing from being the only
// record that a method exists, and to make the one part that *can* contradict
// the code impossible to get wrong.
//
// Everything the renderer emits is plain MDX text, because that is what the
// search index and every parity check read (`app/lib/mdx-extract.ts`). A remark
// plugin expanding this at compile time would be invisible to both.

import { SDK_PROFILES } from "../../app/lib/sdk-registry.ts";
import { GROUPS, isConstructor, placementOf, SOURCES } from "./inventory.mjs";

/** Longest one-line signature before parameters break onto their own lines. */
const WRAP_AT = 72;

export const BANNER =
  "{/* GENERATED by scripts/api/sync.mjs — run `pnpm sync:api`. Edit the SDK's declarations, not this block. */}";

function pythonParam(param) {
  return (
    param.name +
    (param.type ? `: ${param.type}` : "") +
    (param.default === null ? "" : ` = ${param.default}`)
  );
}

function typescriptParam(param) {
  return (
    param.name +
    (param.default === "optional" ? "?" : "") +
    (param.type ? `: ${param.type}` : "")
  );
}

function javaParam(param) {
  return param.type ? `${param.type} ${param.name}` : param.name;
}

const PARAM_FORM = {
  python: pythonParam,
  node: typescriptParam,
  java: javaParam,
};

/**
 * The declaration as that language writes it, wrapped when it runs long.
 *
 * Python and TypeScript are written in call form (`queue.enqueue(…)`) because
 * that is how the docs and the code read. Java is written in declaration form
 * — a return type in front of a receiver (`boolean flexiq.ackMessage(…)`) is
 * not Java, and javadoc is what a Java reader is used to.
 */
function callForm(sdk, symbol, receiver) {
  // A static is reached through its type, never through an instance: a caller
  // has no `ctx` until `JobContext.current()` has handed them one.
  const isStatic = symbol.kind === "static";
  const prefix =
    sdk === "java" || !receiver ? "" : `${isStatic ? symbol.owner : receiver}.`;
  if (symbol.kind === "property") {
    const type = symbol.returns ?? (sdk === "python" ? "Any" : "unknown");
    return sdk === "java"
      ? `${type} ${symbol.name}()`
      : `${prefix}${symbol.name}: ${type}`;
  }
  const params = symbol.params.map(PARAM_FORM[sdk]);
  const ctor = isConstructor(symbol);
  const declared = [
    ...(symbol.deprecated ? ["@Deprecated"] : []),
    ...(isStatic ? ["static"] : []),
    symbol.typeParams,
    symbol.returns ?? "void",
  ].filter(Boolean);
  const head = ctor
    ? symbol.owner
    : sdk === "java"
      ? `${declared.join(" ")} ${symbol.name}`
      : `${prefix}${symbol.name}`;
  const tail =
    ctor || sdk === "java"
      ? ""
      : sdk === "python"
        ? symbol.returns
          ? ` -> ${symbol.returns}`
          : ""
        : `: ${symbol.returns ?? "void"}`;
  const flat = `${head}(${params.join(", ")})${tail}`;
  if (flat.length <= WRAP_AT || params.length === 0) {
    return flat;
  }
  return `${head}(\n${params.map((param) => `    ${param}`).join(",\n")}\n)${tail}`;
}

/** The name a heading gives a symbol — the call form, not the declaring type. */
export function displayName(symbol) {
  const { receiver } = placementOf(symbol);
  if (isConstructor(symbol)) {
    return `${symbol.owner}()`;
  }
  const call = symbol.kind === "property" ? "" : "()";
  const target = symbol.kind === "static" ? symbol.owner : receiver;
  return `${target ? `${target}.` : ""}${symbol.name}${call}`;
}

/**
 * One entry: every overload of one symbol, in a single fence.
 *
 * Deliberately not a parameter table beside it. Names, types and defaults are
 * already in the signature, so a generated table would repeat it column for
 * column; the column that would make a table worth reading is Description, and
 * that is prose the hand-written page owns.
 *
 * `symbols` are the declarations sharing an owner and a name.
 */
export function renderEntry(sdk, symbols, { heading = null } = {}) {
  const { receiver } = placementOf(symbols[0]);
  const lines = [];
  if (heading) {
    lines.push(`${heading} \`${displayName(symbols[0])}\``, "");
  }
  lines.push(
    `\`\`\`${SOURCES[sdk].language}`,
    ...symbols.map((symbol) => callForm(sdk, symbol, receiver)),
    "```",
  );
  return lines.join("\n");
}

/** Group symbols into `owner|name` entries, preserving declaration order. */
export function entriesOf(symbols) {
  const byKey = new Map();
  for (const symbol of symbols) {
    const key = `${symbol.owner ?? ""}|${symbol.name}`;
    byKey.set(key, [...(byKey.get(key) ?? []), symbol]);
  }
  return [...byKey.values()];
}

/** Where the page came from — one line for a single file, a list otherwise. */
function sourceNote(sdk) {
  const { files } = SOURCES[sdk];
  return files.length === 1
    ? [`Generated from \`${files[0]}\`.`]
    : ["Generated from:", "", ...files.map((file) => `- \`${file}\``)];
}

/** One generated reference page: every symbol of one group, one `###` each. */
export function renderGroupPage(sdk, group, symbols) {
  const owners = [
    ...new Set(symbols.map((symbol) => symbol.owner ?? "module")),
  ];
  const body = [];
  for (const owner of owners) {
    const mine = symbols.filter(
      (symbol) => (symbol.owner ?? "module") === owner,
    );
    body.push(`## ${owner}`, "");
    for (const entry of entriesOf(mine)) {
      body.push(renderEntry(sdk, entry, { heading: "###" }), "");
    }
  }
  return [
    "---",
    `title: ${GROUPS[group]}`,
    `description: "Every ${GROUPS[group].toLowerCase()} symbol the ${SDK_PROFILES[sdk].label} SDK declares, with its exact signature."`,
    "---",
    "",
    BANNER,
    "",
    "Signatures, parameters, defaults and return types come straight from the",
    "declarations, so they cannot drift from the code. Prose, examples and gotchas",
    "live on the hand-written pages this section sits beside.",
    "",
    ...sourceNote(sdk),
    "",
    ...body,
  ]
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .concat("\n");
}

/** The section landing page: what this is, and how many symbols are in it. */
export function renderIndexPage(sdk, byGroup) {
  const rows = [...byGroup]
    .filter(([, symbols]) => symbols.length > 0)
    .map(
      ([group, symbols]) =>
        `| [${GROUPS[group]}](/${sdk}/api-reference/symbols/${group}) | ${symbols.length} |`,
    );
  return [
    "---",
    "title: Symbol Index",
    'description: "Every declared symbol, with the signature generated from the SDK\'s own declarations."',
    "---",
    "",
    BANNER,
    "",
    "The complete declared surface. A symbol that exists in the SDK appears here",
    "whether or not a guide has been written for it yet — that is the point:",
    "`pnpm check:parity` fails when this index and the declarations disagree.",
    "",
    ...sourceNote(sdk),
    "",
    "| Page | Symbols |",
    "|---|---|",
    ...rows,
    "",
  ].join("\n");
}

/** Nav for the generated section. */
export function renderMeta(groups) {
  return `${JSON.stringify(
    { title: "Symbol Index", pages: ["index", ...groups] },
    null,
    2,
  )}\n`;
}
